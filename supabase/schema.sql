-- Booking policies
alter table public.booking_requests
  drop constraint if exists booking_requests_status_check;

-- Normalize values from older versions before validating the new status set.
update public.booking_requests
set status = case lower(trim(status))
  when 'accepted' then 'confirmed'
  when 'under review' then 'under_review'
  when 'in review' then 'under_review'
  when 'declined' then 'rejected'
  when 'cancelled' then 'rejected'
  when '' then 'pending'
  else lower(trim(status))
end
where status is distinct from lower(trim(status))
   or lower(trim(status)) in ('accepted', 'under review', 'in review', 'declined', 'cancelled', '');

alter table public.booking_requests
  add constraint booking_requests_status_check
  check (status in ('pending', 'under_review', 'confirmed', 'rejected', 'completed'));

alter table public.booking_requests
  alter column status set default 'pending';

