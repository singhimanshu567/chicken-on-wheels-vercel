create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  email text not null,
  role text not null default 'user' check (role in ('user', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.booking_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  event_date text not null,
  event_time text,
  guest_count integer,
  event_type text,
  location text not null,
  details text,
  status text not null default 'pending',
  admin_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Add fields when upgrading a booking_requests table created by an older schema.
alter table public.booking_requests
  add column if not exists event_time text,
  add column if not exists guest_count integer,
  add column if not exists event_type text,
  add column if not exists details text,
  add column if not exists admin_note text;

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  items jsonb not null default '[]'::jsonb,
  subtotal numeric(10,2) not null default 0,
  total numeric(10,2) not null default 0,
  status text not null default 'pending' check (status in ('pending', 'confirmed', 'completed', 'cancelled')),
  customer_note text,
  item_count integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.truck_schedule (
  id bigint generated by default as identity primary key,
  service_date date not null unique,
  status text not null default 'opening_soon' check (status in ('open', 'closed', 'opening_soon')),
  location_name text not null,
  address text,
  schedule text,
  directions_url text,
  map_embed_url text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  reviewer_name text not null,
  rating integer not null check (rating between 1 and 5),
  quote text not null,
  source text,
  created_at timestamptz not null default now()
);

create index if not exists booking_requests_user_id_idx
  on public.booking_requests(user_id);

create index if not exists booking_requests_status_idx
  on public.booking_requests(status);

create index if not exists orders_user_id_idx
  on public.orders(user_id);

create index if not exists orders_status_idx
  on public.orders(status);

create index if not exists truck_schedule_service_date_idx
  on public.truck_schedule(service_date);

